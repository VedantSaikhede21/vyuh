// Renders the product's own pictures from the real scene (UI plan §3.8): for each
// library scenario a 1920 px hero and a 640 px card, into public/renders/. Re-run
// after any terrain or scene change:
//
//   pnpm dev                                    # web :3000
//   pnpm --filter @vyuh/web render:stills [S05 S06 ...]

import { mkdirSync, statSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium, type Page } from '@playwright/test';

const BASE = process.env.E2E_BASE_URL ?? 'http://localhost:3000';
const OUT = resolve(import.meta.dirname, '../public/renders');
const CODES = Array.from({ length: 15 }, (_, i) => `S${String(i + 1).padStart(2, '0')}`);
/** Terrain textures fade in over 0.4 s; the shadow bake takes under a second. */
const SETTLE_MS = 3500;
const HIDE_DEV = 'nextjs-portal { display: none !important; }';

async function grab(page: Page, code: string, shot: string, width: number, height: number) {
  await page.setViewportSize({ width, height });
  await page.goto(`${BASE}/dev/render?s=${code}&shot=${shot}`);
  await page.addStyleTag({ content: HIDE_DEV });
  await page.getByTestId('render-ready').waitFor({ timeout: 120_000 });
  await page.waitForTimeout(SETTLE_MS);
  const path = resolve(OUT, `${code}-${shot}-${width}.jpg`);
  await page.screenshot({ path, type: 'jpeg', quality: 80 });
  console.log(`${code} ${shot} ${width}: ${Math.round(statSync(path).size / 1024)} KB`);
}

const browser = await chromium.launch({
  channel: 'chrome',
  headless: true,
  args: ['--use-angle=d3d11', '--enable-gpu', '--ignore-gpu-blocklist'],
});
const page = await browser.newPage();
mkdirSync(OUT, { recursive: true });
const codes = process.argv.slice(2).length > 0 ? process.argv.slice(2) : CODES;
for (const code of codes) {
  await grab(page, code, 'establishing', 1920, 1080);
  await grab(page, code, 'establishing', 640, 360);
}
await browser.close();
writeFileSync(
  resolve(OUT, 'README.md'),
  '# Renders\n\nGenerated by `pnpm --filter @vyuh/web render:stills` from the real scene. Do not edit.\n',
);
